// Generates a base64 Data URL for an SVG avatar
export function getAvatarDataUrl(avatarId) {
  const avatar = BUILT_IN_AVATARS.find(a => a.id === avatarId) || BUILT_IN_AVATARS[0];
  return `data:image/svg+xml;utf8,${encodeURIComponent(avatar.svg)}`;
}
